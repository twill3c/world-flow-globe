"""グリッドの補正台帳 —— 通路と運河(SPEC.md §6.1.1)。

0.5 度・面積割合 0.5 のマスクは、**実在する狭い海峡を 2 つ塞ぐ**。
塞がったところは黙って諦めず、**名前つきの通路**として開ける。

## 通路を足してよい条件

**通路は「海峡」にだけ足す。河川をさかのぼる港には足さない。**
0.5 度の海洋グリッドは河川を表せないので、河川港(フィラデルフィア・ニューオーリンズ・
モントリオール・マナウス等)は「経路に使えない港」として理由つきで運ぶ。
これらに通路を足し始めると、どこで止めるかの線が引けなくなる。

海峡に足すのは、次のどちらかに当たるときだけ。

- **世界の連結性**に効く(ジブラルタル・ダーダネルス・スエズ湾)
- 閉じ込められた水域に **``outflows`` 上位 100 位以内の港**がある
  (ファン・デ・フカ海峡 —— バンクーバー 61 位・シアトル 71 位)

台帳に載せる条件は次のとおり。緩めないために、テストで両方向から押さえる。

- 通路(``PASSAGES``): 補正前に**実際に塞がっていること**を測って確かめる。
  塞がっていない通路を台帳に残すと、検査は緑のまま台帳だけが嘘になる。
- 運河(``CANALS``): 補正前に地峡が**実際に塞がっていること**を確かめる。
  塞がっていなければ、運河を閉じても船が抜けるので、運河は何も意味しない。

**通路と運河は別物である。**

- 通路は「地図の粗さのせいで塞がった実在の海路」を開けるもの。閉じられない。
- 運河は「人が掘ったので通れる地峡」を貫くもの。**シナリオで閉じられる。**
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Passage:
    """グリッドの粗さで塞がった実在の海路を開ける、セル中心どうしの辺。"""

    id: str
    name: str
    #: 開ける辺の両端(lon, lat)。中心がこのセルに入る 2 セルを繋ぐ。
    a: tuple[float, float]
    b: tuple[float, float]
    #: なぜ必要か(実測を書く)。
    reason: str
    #: 中継点。狭い水路が長いときに、途中のセルも航行可能へ倒す。
    via: tuple[tuple[float, float], ...] = ()
    #: どちらの条件で載せたか。``connectivity`` か ``major_port``。
    criterion: str = "connectivity"


@dataclass(frozen=True)
class Canal:
    """人が掘った水路。地峡を貫く辺で、シナリオで閉じられる。"""

    id: str
    chokepoint_id: str
    name: str
    a: tuple[float, float]
    b: tuple[float, float]
    #: 実際の運河の全長(km)。辺の重みにこれを使う ——
    #: セル中心間の測地線距離ではなく、**運河そのものの長さ**が正しい。
    length_km: float
    length_source: str
    via: tuple[tuple[float, float], ...] = ()


